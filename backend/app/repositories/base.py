"""
Repository abstraction layer.
All data access goes through these abstract base classes.
Swap the concrete implementation (MemoryRepository / FirestoreRepository)
without touching any business logic.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Optional

from ..models import (
    Approval,
    AuditRecord,
    Conversation,
    Department,
    Document,
    Guideline,
    Incident,
    LearningResource,
    Meeting,
    Message,
    Notification,
    Project,
    Task,
    UserLearningProgress,
    UserProfile,
)


class UserRepository(ABC):
    @abstractmethod
    async def get(self, user_id: str) -> Optional[UserProfile]: ...
    @abstractmethod
    async def get_by_email(self, email: str) -> Optional[UserProfile]: ...
    @abstractmethod
    async def list(self, skip: int = 0, limit: int = 20) -> tuple[list[UserProfile], int]: ...
    @abstractmethod
    async def create(self, user: UserProfile) -> UserProfile: ...
    @abstractmethod
    async def update(self, user: UserProfile) -> UserProfile: ...
    @abstractmethod
    async def delete(self, user_id: str) -> bool: ...
    @abstractmethod
    async def list_reports(self, manager_id: str) -> list[UserProfile]: ...


